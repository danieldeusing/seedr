#!/usr/bin/env node
/* global console */
// Writes functions/registry-keys.generated.ts: the set of `type/slug` keys from the
// compiled registry manifests. The install-statistics API validates incoming events
// against it, so fabricated items are rejected with 404 instead of being recorded.
// A flat Set of short strings keeps the Functions bundle small no matter how much
// metadata the manifests carry. Regenerated before typecheck, test and build.
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const webRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const registryDir = join(webRoot, "..", "..", "registry");
const index = JSON.parse(readFileSync(join(registryDir, "manifest.json"), "utf8"));

const keys = [];
for (const [type, descriptor] of Object.entries(index.types)) {
  const manifest = JSON.parse(readFileSync(join(registryDir, descriptor.file), "utf8"));
  for (const item of manifest.items) {
    if (item.type !== type) throw new Error(`${descriptor.file}: item ${item.slug} has type ${item.type}`);
    if (!/^[a-z0-9][a-z0-9._-]{0,99}$/.test(item.slug)) throw new Error(`${descriptor.file}: slug "${item.slug}" is not URL-safe`);
    keys.push(`${type}/${item.slug}`);
  }
}
keys.sort();

const source =
  "// GENERATED by scripts/generate-registry-keys.mjs from registry/*/manifest.json — do not edit.\n" +
  `// ${keys.length} items, registry manifest version ${index.version}.\n` +
  "export const REGISTRY_KEYS: ReadonlySet<string> = new Set([\n" +
  keys.map((key) => `  ${JSON.stringify(key)},`).join("\n") +
  "\n]);\n";

const outFile = join(webRoot, "functions", "registry-keys.generated.ts");
if (!existsSync(outFile) || readFileSync(outFile, "utf8") !== source) {
  writeFileSync(outFile, source);
  console.log(`wrote functions/registry-keys.generated.ts (${keys.length} items)`);
}
